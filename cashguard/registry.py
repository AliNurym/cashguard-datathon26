def describe(vtype: str, t: float, details: dict | None = None) -> dict:
    r = REGISTRY.get(vtype)
    if r is None:
        return {"type": vtype, "description": "", "norm": ""}
    tpl = VARIANTS.get((vtype, (details or {}).get("kind")), r["template"])
    return {"type": r["name"], "description": tpl.format(t=t), "norm": r["norm"]}
